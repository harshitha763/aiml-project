import { useEffect, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import {
  FileText, Users, Clock, Calendar, CheckSquare, ListTodo,
  AlertCircle, ArrowRight, Download, Mail, Sparkles, Building,
} from 'lucide-react'
import { meetingsApi, exportApi, downloadBlob } from '../services/api'
import type { Meeting, MeetingReport, ActionItem, Summary } from '../types'
import { FullSpinner } from '../components/Spinner'
import { EmptyState } from '../components/EmptyState'
import { formatDate, formatDuration } from '../utils/cn'

export function MeetingMinutes() {
  const navigate = useNavigate()
  const [meetings, setMeetings] = useState<Meeting[]>([])
  const [selectedId, setSelectedId] = useState('')
  const [report, setReport] = useState<MeetingReport | null>(null)
  const [actions, setActions] = useState<ActionItem[]>([])
  const [summary, setSummary] = useState<Summary | null>(null)
  const [loading, setLoading] = useState(true)
  const [generating, setGenerating] = useState(false)

  useEffect(() => {
    const load = async () => {
      setLoading(true)
      try {
        const res = await meetingsApi.list(1, 50)
        setMeetings(res.items || [])
      } catch { /* ignore */ }
      finally { setLoading(false) }
    }
    load()
  }, [])

  const loadMeeting = async (id: string) => {
    setSelectedId(id)
    if (!id) { setReport(null); setActions([]); setSummary(null); return }
    try {
      const [r, a, s] = await Promise.all([
        meetingsApi.getReport(id).catch(() => null),
        meetingsApi.listActionItems(id).catch(() => []),
        meetingsApi.getSummary(id).catch(() => null),
      ])
      setReport(r as MeetingReport | null)
      setActions(a as ActionItem[])
      setSummary(s as Summary | null)
    } catch { /* ignore */ }
  }

  const handleExport = (format: 'txt' | 'pdf') => {
    if (!selectedId) return
    exportApi.meetingReport(selectedId, format).then(b => downloadBlob(b, `minutes_${selectedId}.${format}`))
  }

  const handleGenerateSummary = async () => {
    if (!selectedId) return
    setGenerating(true)
    try {
      const s = await meetingsApi.generateSummary(selectedId)
      setSummary(s)
      const r = await meetingsApi.getReport(selectedId)
      setReport(r as MeetingReport | null)
    } catch { /* ignore */ }
    finally { setGenerating(false) }
  }

  if (loading) return <FullSpinner message="Loading meetings…" />

  return (
    <div className="space-y-6 animate-slide-up">
      <div className="flex items-center justify-between">
        <div>
          <h1 className="text-2xl font-bold text-white">Meeting Minutes</h1>
          <p className="text-sm text-slate-400 mt-0.5">Formal minutes with structured reports</p>
        </div>
        {selectedId && (
          <div className="flex gap-2">
            <button onClick={() => handleExport('txt')} className="btn-secondary text-sm"><Download size={14} /> TXT</button>
            <button onClick={() => handleExport('pdf')} className="btn-secondary text-sm"><Download size={14} /> PDF</button>
          </div>
        )}
      </div>

      {/* Meeting selector */}
      <div className="card">
        <label className="block text-sm text-slate-300 mb-1.5">Select a meeting</label>
        <select className="input" value={selectedId} onChange={(e) => loadMeeting(e.target.value)}>
          <option value="">Choose a meeting…</option>
          {meetings.map(m => <option key={m.id} value={m.id}>{m.title}</option>)}
        </select>
      </div>

      {!selectedId ? (
        <div className="card">
          <EmptyState icon={FileText} title="No meeting selected" message="Select a meeting above to view formal minutes with a structured report." />
        </div>
      ) : !report ? (
        <div className="card">
          <EmptyState icon={FileText} title="No report generated" message="Generate a summary first to create meeting minutes." actionLabel={generating ? 'Generating…' : 'Generate Summary'} onAction={handleGenerateSummary} />
        </div>
      ) : (
        <>
          {summary?.is_demo && <div className="badge-warning mb-2">Demo content — not generated by a real AI</div>}

          {/* Formal Minutes Document */}
          <div className="card max-w-4xl" style={{ background: 'rgba(255,255,255,0.04)' }}>
            {/* Header */}
            <div className="text-center pb-6 mb-6 border-b border-white/10">
              <div className="flex items-center justify-center gap-2 mb-3">
                <Building size={20} className="text-violet-400" />
                <span className="text-xs uppercase tracking-widest text-slate-500">Meeting Minutes</span>
              </div>
              <h2 className="text-2xl font-bold text-white mb-2">{report.title}</h2>
              <div className="flex items-center justify-center flex-wrap gap-4 text-sm text-slate-400">
                <span className="flex items-center gap-1"><Calendar size={14} /> {formatDate(report.date)}</span>
                <span className="flex items-center gap-1"><Clock size={14} /> {formatDuration(report.duration_minutes)}</span>
                <span className="flex items-center gap-1"><Users size={14} /> {report.participants || 'Unspecified'}</span>
              </div>
            </div>

            {/* Executive Summary */}
            <div className="mb-6">
              <h3 className="text-sm font-bold uppercase tracking-wider text-violet-400 mb-2 flex items-center gap-2">
                <FileText size={15} /> Executive Summary
              </h3>
              <p className="text-sm text-slate-200 leading-relaxed whitespace-pre-wrap">{report.executive_summary}</p>
            </div>

            {/* Purpose */}
            {report.purpose && (
              <div className="mb-6">
                <h3 className="text-sm font-bold uppercase tracking-wider text-cyan-400 mb-2">Meeting Purpose</h3>
                <p className="text-sm text-slate-200 leading-relaxed">{report.purpose}</p>
              </div>
            )}

            {/* Main Topics */}
            {report.main_topics.length > 0 && (
              <div className="mb-6">
                <h3 className="text-sm font-bold uppercase tracking-wider text-indigo-400 mb-2">Main Topics Discussed</h3>
                <ul className="space-y-1.5">
                  {report.main_topics.map((t, i) => (
                    <li key={i} className="text-sm text-slate-200 flex gap-2">
                      <span className="text-indigo-400 font-mono text-xs mt-0.5">{(i + 1).toString().padStart(2, '0')}</span>
                      {t}
                    </li>
                  ))}
                </ul>
              </div>
            )}

            {/* Decisions */}
            {report.decisions.length > 0 && (
              <div className="mb-6">
                <h3 className="text-sm font-bold uppercase tracking-wider text-emerald-400 mb-2 flex items-center gap-2">
                  <CheckSquare size={15} /> Decisions Made
                </h3>
                <ul className="space-y-1.5">
                  {report.decisions.map((d, i) => (
                    <li key={i} className="text-sm text-slate-200 flex gap-2">
                      <CheckSquare size={14} className="text-emerald-400 mt-0.5 shrink-0" />
                      {d}
                    </li>
                  ))}
                </ul>
              </div>
            )}

            {/* Action Items */}
            {report.action_items.length > 0 && (
              <div className="mb-6">
                <h3 className="text-sm font-bold uppercase tracking-wider text-amber-400 mb-2 flex items-center gap-2">
                  <ListTodo size={15} /> Action Items
                </h3>
                <div className="space-y-2">
                  {report.action_items.map((a, i) => (
                    <div key={i} className="flex items-start gap-3 p-3 rounded-xl bg-white/[0.03] border border-white/5">
                      <span className="text-xs font-mono text-amber-400 mt-0.5 shrink-0">#{i + 1}</span>
                      <div className="flex-1">
                        <div className="text-sm text-white">{a.description}</div>
                        <div className="flex gap-3 mt-1 text-xs text-slate-500">
                          <span>Owner: <span className="text-slate-300">{a.owner}</span></span>
                          {a.due_date && <span>Due: <span className="text-slate-300">{formatDate(a.due_date)}</span></span>}
                          <span className={a.completed ? 'text-emerald-400' : 'text-amber-400'}>{a.completed ? '✓ Done' : '○ Pending'}</span>
                        </div>
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            )}

            {/* Unresolved Questions */}
            {report.unresolved_questions.length > 0 && (
              <div className="mb-6">
                <h3 className="text-sm font-bold uppercase tracking-wider text-orange-400 mb-2 flex items-center gap-2">
                  <AlertCircle size={15} /> Unresolved Questions
                </h3>
                <ul className="space-y-1.5">
                  {report.unresolved_questions.map((q, i) => (
                    <li key={i} className="text-sm text-slate-200 flex gap-2">
                      <AlertCircle size={14} className="text-orange-400 mt-0.5 shrink-0" />
                      {q}
                    </li>
                  ))}
                </ul>
              </div>
            )}

            {/* Next Steps */}
            {report.next_steps.length > 0 && (
              <div className="mb-6">
                <h3 className="text-sm font-bold uppercase tracking-wider text-cyan-400 mb-2">Next Steps</h3>
                <ul className="space-y-1.5">
                  {report.next_steps.map((s, i) => (
                    <li key={i} className="text-sm text-slate-200 flex gap-2">
                      <ArrowRight size={14} className="text-cyan-400 mt-0.5 shrink-0" />
                      {s}
                    </li>
                  ))}
                </ul>
              </div>
            )}

            {/* Responsible People */}
            {report.responsible_people.length > 0 && (
              <div className="mb-6">
                <h3 className="text-sm font-bold uppercase tracking-wider text-pink-400 mb-2">Responsible People</h3>
                <div className="flex flex-wrap gap-2">
                  {report.responsible_people.map((p, i) => (
                    <span key={i} className="badge-primary">{p}</span>
                  ))}
                </div>
              </div>
            )}

            {/* Footer */}
            <div className="pt-4 border-t border-white/10 flex items-center justify-between text-xs text-slate-500">
              <span>Generated by IntelliMeet AI</span>
              <span>{formatDate(new Date().toISOString())}</span>
            </div>
          </div>

          <div className="flex gap-2">
            <button onClick={handleGenerateSummary} disabled={generating} className="btn-secondary text-sm">
              <Sparkles size={14} /> {generating ? 'Generating…' : 'Regenerate Summary'}
            </button>
            <button onClick={() => navigate(`/meetings/${selectedId}`)} className="btn-secondary text-sm">
              View Full Meeting <ArrowRight size={14} />
            </button>
          </div>
        </>
      )}
    </div>
  )
}
